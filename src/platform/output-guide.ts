import { Effect, FileSystem, Path } from "effect"
import { isNotFound, toFileError, writePrivateFile } from "./files.ts"

const MARKER = "<!-- Generated by prompt-profile: output guide -->"
const GUIDE = `${MARKER}
# Your prompt-profile output

Open **index.html** to browse completed reports, newest first. Inside a report
folder, open **report.html** directly. Both work offline without a server.
Only files relevant to the commands you ran will be present.

## What the files mean

| File or folder | Purpose |
| --- | --- |
| index.html | The report library: start here to find the latest report. |
| reports/<timestamp>-<id>/ | One completed analysis. Each new analysis gets its own folder. |
| reports/legacy-<id>/ | A preserved report from an older output layout. |
| report.html | The readable report, with a language switch when available. |
| card.png | The summary image in the report's first language. |
| card.<language>.png | Additional language images, such as card.en.png. A missing card does not mean the HTML report failed. |
| profile.json | The analysis data. Keep this to render supported profiles again without another LLM analysis. Older formats may require the package version that created them. |
| run.json | Completion metadata: time, engine, languages, coverage and card status. Keep with the completed report. |
| render.json | Rendering choices, version, profile fingerprint and relative source path. |
| variants/<name>/ | Alternative renders. Each contains its own report, profile, rendering metadata and available cards. Rendering the same variant again replaces its generated files. |
| library.json | Rebuildable catalog of completed reports; it is not the analysis itself. |
| executions/<id>/summary.json | Execution status, call accounting and recovery information, including failed or interrupted runs. These are separate from completed reports. |
| stats.json | Statistics-only output from the stats command; replaced the next time stats uses this folder. |
| plan.json and chunks/ | Dry-run estimate and redacted text prepared for analysis. Use a separate output folder for each dry run; later runs may leave older chunks. |
| README.md | This generated guide. Your own existing README is left untouched. |

## Dates and names

New analysis folders use the computer's local time, for example
2026-11-01_03-12-04+0800-<id>: November 1, 2026 at 03:12:04, UTC+08:00.
The final ID prevents collisions. Older names such as 20261031T191204Z-<id>
use UTC (Z); they represent the same instant in this example. JSON timestamps
remain in machine-readable formats. The library orders reports by completion
time, so use index.html rather than sorting mixed old and new folder names.

## Keep, move or delete

- Back up or move the whole output folder to preserve relative links. Copy a
  complete report folder when archiving one analysis; its link back to the library
  needs the original surrounding layout. Do not rename report folders or edit IDs.
- To remove an analysis, delete its whole folder under reports/, including any
  variants you no longer need. This permanently removes that saved analysis.
  Never delete profile.json or run.json alone from a report you want to keep.
- After deleting reports, rebuild index.html and library.json without an LLM call:

      prompt-profile history --out "<output-folder>"

- Unwanted variants, stats.json, dry-run plan.json and chunks/ can be deleted
  independently. Keep profile.json if you want to render a variant again.
- Execution folders can be deleted independently when their diagnostics are no
  longer needed. Deleting them does not remove completed reports or the separate
  analysis cache; keep them while troubleshooting an interrupted run.
- Hidden reports/.pending-* folders are unfinished output. Remove them only after
  confirming that no prompt-profile process is using this output folder.
- Older root-level report files and variants may have been copied to a legacy
  archive. Remove originals only after verifying that the archived copies match.

These files contain personal analysis and may include prompt excerpts, local paths
or redacted input. Review the files you choose to share. Render and history commands
work locally; neither requires another LLM analysis. No saved report history is
pruned automatically.
`

/** Refresh our generated guide without replacing user notes or following README symlinks. */
export const writeOutputGuide = (root: string) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    const path = yield* Path.Path
    const file = path.join(root, "README.md")
    const info = yield* fs.lstat(file).pipe(Effect.catchIf(isNotFound, () => Effect.succeed(null)))
    if (info !== null) {
      if (info.type !== "File" || info.size > 64_000n) return
      const text = yield* fs.readFileString(file)
      if (!text.startsWith(`${MARKER}\n`)) return
    }
    yield* writePrivateFile(fs, path, file, GUIDE)
  }).pipe(Effect.mapError(toFileError(root)))
